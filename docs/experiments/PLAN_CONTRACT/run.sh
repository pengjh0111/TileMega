#!/usr/bin/env bash
# SPDX-License-Identifier: BSD-3-Clause
# EX-E1 gates E1-a (H2) and E1-b (H3).
#
# Two harnesses are compiled against the same generated sources and the same
# libtilemega.a: the R2 baseline host, taken from 6c359e2b, and the working
# tree, which resolves a PlacementMode and walks `plan.queue[worker]` in sigma
# order.  The TILEMEGA_PLAN_DUMP block that writes the three TSVs is lifted
# verbatim from the working-tree harness into the baseline copy, so a
# byte-identical dump is evidence about the placement and not about the dumper.
#
# E1-a additionally diffs the generated .cu itself: a variant that carries no
# plan must be emitted exactly as the pre-plan generator emitted it.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "${here}/../../.." && pwd)"
build="${BUILD_DIR:-${repo}/build-portable}"
nvcc="${CUDACXX:-/usr/local/cuda/bin/nvcc}"
baseline="${BASELINE:-6c359e2b}"
work="${WORK_DIR:-/tmp/plan_contract}"
rm -rf "${work}"; mkdir -p "${work}/inc" "${work}/bin" "${work}/dump" "${work}/log"

# The baseline include tree: 6c359e2b's harness, plus this tree's dump block.
cp -r "${repo}/include/." "${work}/inc/"
git -C "${repo}" show "${baseline}:include/tilemega/Codegen/tasks/ModelHarness.cuh" \
  > "${work}/inc/tilemega/Codegen/tasks/ModelHarness.cuh"
python3 - "${repo}" "${work}/inc/tilemega/Codegen/tasks/ModelHarness.cuh" <<'PY'
import sys
repo, target = sys.argv[1], sys.argv[2]
current = open(f"{repo}/include/tilemega/Codegen/tasks/ModelHarness.cuh").read()
start = current.index("  // A deterministic view of what the Plan materialized")
end = current.index("\n  }\n", current.index('TILEMEGA_PLAN_DUMP')) + len("\n  }\n")
block = current[start:end]
base = open(target).read()
# Immediately before the harness returns the assembled model, which is where
# the working tree writes it too.
anchor = base.rindex("  return model;")
open(target, "w").write(base[:anchor] + block + base[anchor:])
PY

common=(-std=c++17 -O2 -arch=native -lineinfo -DTILEMEGA_EVENT_KAPPA=1
  -I"${repo}/third_party/cutlass/include"
  -I"${repo}/third_party/cutlass/tools/util/include"
  -I"${repo}/third_party/cutlass/test")
link=("${build}/libtilemega.a" -L/usr/local/cuda/lib64 -lcudart)

# --- the generated sources, from this tree's compiler.  Mode 4 needs the
# variant to ask for the balanced L-sched writeback, so it gets its own source;
# modes 0 and 5 are selected by the macro alone.
variants="${repo}/docs/experiments/OWNERSHIP/plan_structured.json"
python3 - "${variants}" "${work}/variants_balanced.json" <<'BALANCED'
import json, sys
plan = json.load(open(sys.argv[1]))
plan['variants'][0]['balanced_placement'] = True
json.dump(plan, open(sys.argv[2], 'w'), indent=1)
BALANCED
for model in gqa2 mha4; do
  "${build}/tools/tilemega-compile" \
    "${repo}/docs/experiments/SEQSCAN/raw/export/${model}.json" \
    "${work}/${model}.cu" --variants "${variants}" \
    > "${work}/log/gen_${model}.txt" 2>&1
  "${build}/tools/tilemega-compile" \
    "${repo}/docs/experiments/SEQSCAN/raw/export/${model}.json" \
    "${work}/${model}_balanced.cu" --variants "${work}/variants_balanced.json" \
    > "${work}/log/gen_${model}_balanced.txt" 2>&1
done

# --- E1-a: a plan-free variant is generated byte for byte as before, and the
# balanced one differs only by the plan fields (the positive control, so an
# empty diff above cannot be explained by the plan never being emitted).
for model in gqa2 mha4; do
  diff "${here}/legacy_identity/baseline/${model}.cu" "${work}/${model}.cu" \
    > "${work}/log/e1a_${model}.diff" || true
  if [ -f "${here}/legacy_identity/baseline/${model}_balanced.cu" ]; then
    diff "${here}/legacy_identity/baseline/${model}_balanced.cu" \
      "${work}/${model}_balanced.cu" > "${work}/log/e1a_${model}_balanced.diff" || true
  fi
  diff "${work}/${model}.cu" "${work}/${model}_balanced.cu" \
    > "${work}/log/plan_emission_${model}.diff" || true
done

# --- E1-b: modes 0, 4 and 5 through both harnesses
for model in gqa2 mha4; do
  for place in 0 4 5; do
    src="${work}/${model}.cu"
    [ "${place}" = 4 ] && src="${work}/${model}_balanced.cu"
    for side in base plan; do
      inc=("-I${repo}/include")
      [ "${side}" = base ] && inc=("-I${work}/inc" "-I${repo}/include")
      "${nvcc}" "${common[@]}" "${inc[@]}" -DTILEMEGA_PLACEMENT="${place}" \
        "${src}" "${link[@]}" -o "${work}/bin/${side}_${model}_p${place}" \
        2>> "${work}/log/nvcc.log"
    done
  done
done

for model in gqa2 mha4; do
  for place in 0 4 5; do
    for seq in 4 128; do
      for side in base plan; do
        cell="${side}_${model}_p${place}_s${seq}"
        mkdir -p "${work}/dump/${cell}"
        TILEMEGA_PLAN_DUMP="${work}/dump/${cell}" \
          TILEMEGA_PLACEMENT_BASE_DUMP=1 \
          "${work}/bin/${side}_${model}_p${place}" \
          "${repo}/docs/experiments/SEQSCAN/raw/fixture/${model}_s${seq}_p3" \
          > "${work}/dump/${cell}.out" 2>&1
      done
    done
  done
done

# --- the two verdicts, as data
: > "${work}/sha256.txt"
for d in "${work}/dump"/*/; do
  cell="$(basename "${d}")"
  (cd "${d}" && sha256sum ./*.tsv | sed "s|^|${cell} |") >> "${work}/sha256.txt"
done

# E1-a
for model in gqa2 mha4; do
  n="$(wc -l < "${work}/log/e1a_${model}.diff")"
  echo "E1-a ${model}: $([ "${n}" -eq 0 ] && echo PASS || echo FAIL) (${n} diff lines)"
  echo "     plan emission control ${model}: $(grep -c '^>' "${work}/log/plan_emission_${model}.diff") added lines"
done

# E1-b: every cell's base and plan hashes must agree, file by file
python3 - "${work}/sha256.txt" <<'VERDICT'
import sys, collections
rows = collections.defaultdict(dict)
for line in open(sys.argv[1]):
    cell, digest, name = line.split()
    side, rest = cell.split('_', 1)
    rows[(rest, name)][side] = digest
bad = [k for k, v in rows.items() if v.get('base') != v.get('plan')]
print(f"E1-b: {'PASS' if not bad else 'FAIL'} "
      f"({len(rows) - len(bad)}/{len(rows)} dump files byte identical)")
for k in bad:
    print("  MISMATCH", k)
VERDICT

passes="$(grep -lc 'RESULT status=PASS' "${work}/dump"/*.out | wc -l)"
echo "correctness: ${passes}/$(ls "${work}/dump"/*.out | wc -l) runs report RESULT status=PASS"
echo "wrote ${work}/sha256.txt and ${work}/dump"
