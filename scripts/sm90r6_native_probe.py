#!/usr/bin/env python3
"""Generate all legal family geometries and build AB1a stage-ledger probes."""
import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys

from sm90d1_common import ROOT, write
from sm90r6_probe_source import compose,geometry_source
from sm90r3_write_resources import instructions


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def isolated(coordinates, family):
    c = copy.deepcopy(coordinates)
    c['schema'] = 9
    c.setdefault('tp', 1);c.setdefault('argmax', 'la')
    c.setdefault('route', 'local');c.setdefault('combine', 'la')
    c['group_wait'] = False
    c['weight_stream'] = False
    if family in ('expert_gate_up','expert_down','router'):
        c['expert_fuse'] = False;c['route'] = 'stage'
    if family == 'expert_down':c['combine'] = 'stage'
    if family == 'lm_head':c['argmax'] = 'stage'
    if c['model'] == 'dense':
        c['swiglu_u'] = 16
        while c['gemms']['gate_up']['tile_n'] % (2*c['swiglu_u']) and c['swiglu_u'] > 4:
            c['swiglu_u'] //= 2
    return c


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--input', type=Path, required=True)
    p.add_argument('--coordinates', type=Path, required=True)
    p.add_argument('--target', type=Path, required=True)
    p.add_argument('--compiler', type=Path, required=True)
    p.add_argument('--batch', type=int, required=True)
    p.add_argument('--native-probe', required=True)
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--domain-tool', type=Path, default=ROOT/'build/tools/tilemega-native-domains')
    p.add_argument('--entry-limit', type=Path, required=True,
                   help='retained R5 entry-size audit with its twice-maximum probe_limit')
    p.add_argument('--split-compile', type=int, default=4)
    p.add_argument('--reuse-builds',type=Path,
                   help='retained stable probe builds; generated bytes and inputs must match')
    a = p.parse_args()
    a.out = a.out.resolve()
    if a.out.suffix != '.so':p.error('probe output must end in .so')
    directory = Path(str(a.out)+'.probe');directory.mkdir(parents=True,exist_ok=False)
    family = a.native_probe
    original = json.loads(a.coordinates.read_text())
    if original.get('tp',1) != 1 or family not in original['gemms']:
        raise ValueError('native probe needs a TP1 GEMM family from the coordinate')
    limit = json.loads(a.entry_limit.read_text())
    if limit['probe_limit'] != 2*limit['maximum']['instructions']:
        raise ValueError('probe entry limit differs from twice the measured R5 maximum')
    inputs = {str(path.resolve()):sha(path) for path in (a.input,a.coordinates,a.target,a.compiler,
        a.entry_limit,Path(__file__),ROOT/'scripts/sm90r6_probe_source.py',
        ROOT/'include/tilemega/Codegen/tasks/Sm90DenseProbe.cuh')}
    write(directory/'inputs.json', inputs)
    cell = dict(id='probe',seed=str(a.coordinates.resolve()),export=str(a.input.resolve()),batch=a.batch)
    write(directory/'cells.json',[cell])
    with (directory/'domains.log').open('w') as log:
        subprocess.run([str(a.domain_tool),str(a.target),str(directory/'cells.json'),
            str(directory/'domains.jsonl')],cwd=ROOT,stdout=log,stderr=subprocess.STDOUT,check=True)
    catalog = json.loads((directory/'domains.jsonl').read_text())
    domains = [x for x in catalog['domains'] if x['family']==family and x['residency']==original['residency']]
    if len(domains)!=1 or not domains[0]['geometries']:raise ValueError('probe has no legal family domain')
    geometries = [x['geometry'] for x in domains[0]['geometries']]
    sources = []

    def generate(name, coordinates):
        path = directory/name;path.mkdir()
        write(path/'coordinates.json',coordinates)
        command = [str(a.compiler.resolve()),'compile',str(a.input.resolve()),str(path/'decode.cu'),
            '--tmexec-config',str(path/'coordinates.json'),'--runtime-target',str(a.target.resolve()),
            '--batch',str(a.batch),'--serving','decode','--emit','serving']
        write(path/'command.json',command)
        with (path/'generate.log').open('w') as log:
            subprocess.run(command,cwd=ROOT,env=dict(os.environ,CUDA_VISIBLE_DEVICES=''),
                           stdout=log,stderr=subprocess.STDOUT,check=True)
        return path/'decode.cu'

    base = isolated(original,family)
    base_path = generate('base',base)
    for index,geometry in enumerate(geometries):
        c = copy.deepcopy(base);c['gemms'][family]=geometry;c=isolated(c,family)
        part=directory/f'geometry-{index}';part.mkdir()
        write(part/'coordinates.json',c)
        source=part/'leaf.cu'
        source.write_text(geometry_source(base_path.read_text(),base,family,geometry,c['swiglu_u']))
        sources.append((geometry,source.read_text(),c))
        print(json.dumps(dict(family=family,generated=index+1,total=len(geometries))),flush=True)
    source_snapshot = directory/'source-snapshot.json'
    env = dict(os.environ,PYTHONPATH=str(ROOT/'python'),CUDA_VISIBLE_DEVICES='')
    subprocess.run([sys.executable,'-m','tilemega.build.identity','--root',str(ROOT),
        '--snapshot',str(source_snapshot),'--capture','--compiler',str(a.compiler.resolve())],
        cwd=ROOT,env=env,check=True)
    snapshot = json.loads(source_snapshot.read_text())
    for path,digest in snapshot['source_files'].items():
        path = Path(path);inputs[str(path if path.is_absolute() else ROOT/path)] = digest
    write(directory/'inputs.json',inputs)
    retained = [];attempts = [];previous={}
    if a.reuse_builds:
        previous_inputs=json.loads((a.reuse_builds.parent/'inputs.json').read_text())
        for path,digest in previous_inputs.items():
            source=Path(path)
            if source.name in ('sm90r6_native_probe.py','sm90r6_probe_source.py'):
                source=a.reuse_builds.parent/'builder-source'/source.name
            if sha(source)!=digest:raise ValueError('retained probe build input changed: '+str(source))
        for row in json.loads(a.reuse_builds.read_text()):
            if row['status'] in ('compiled','entry_size_split'):
                previous[row['first'],row['last']]=row

    def build(first,last):
        text,ledger=compose(base_path.read_text(),base,sources[first:last],family)
        old=previous.get((first,last))
        if old is not None:
            old_ledger=json.loads(Path(old['ledger']).read_text())
            # Older ledgers lacked this descriptive field; it changes no code.
            old_ledger.setdefault('prefix_execution','unrolled layer-zero prerequisites')
            if (old['source_sha256']!=hashlib.sha256(text.encode()).hexdigest() or
                    sha(old['binary'])!=old['binary_sha256'] or old_ledger!=ledger or
                    old['limit']!=limit['probe_limit'] or not old['inputs_unchanged']):
                raise ValueError('retained probe is not the same generated program')
            record=dict(old,reused_from=str(a.reuse_builds.resolve()))
            attempts.append(record)
            if old['status']=='compiled':retained.append(record)
            else:
                middle=(first+last)//2;build(first,middle);build(middle,last)
            write(directory/'builds.json',attempts)
            return
        name=f'part-{first}-{last}';part=directory/name;part.mkdir()
        binary=part/'probe.so';source=Path(str(binary)+'.cu')
        source.write_text(text);write(part/'ledger.json',ledger)
        command=[str(ROOT/'scripts/run_sm90r1_build.py'),'--receipt',str(part/'build.json'),
            '--max-gib','48','--timeout','5400','--lock','/tmp/tilemega_sm90r2_native_build.lock','--',
            '/usr/local/cuda/bin/nvcc','-rdc=true','-std=c++17','-O3','-gencode','arch=compute_90a,code=sm_90a',
            '--expt-relaxed-constexpr','-shared','-Xcompiler','-fPIC','-cudart','shared','-Xptxas','-v',
            '--split-compile',str(a.split_compile),'-I'+str(ROOT/'include'),
            '-I'+str(ROOT/'third_party/cutlass/include'),str(source),'-o',str(binary)]
        write(part/'command.json',[sys.executable,*command])
        with (part/'ptxas.log').open('w') as log:
            status=subprocess.call([sys.executable,*command],cwd=ROOT,env=env,stdout=log,stderr=subprocess.STDOUT)
        if any(sha(path)!=digest for path,digest in inputs.items()):
            raise ValueError('probe inputs changed during generation or compilation')
        if status:
            # Preserve a failed oversized prototype, but never bisect an
            # arbitrary compiler error that could indicate a generator defect.
            log=(part/'ptxas.log').read_text(errors='replace')
            if last-first>1 and ('sizeof(Binding)+256<32764' in log or 'formal parameter space' in log):
                attempts.append(dict(first=first,last=last,status='binding_size_split'))
                middle=(first+last)//2;build(first,middle);build(middle,last);return
            raise RuntimeError('probe compilation failed: '+str(part/'ptxas.log'))
        entry_output=subprocess.run(['/usr/local/cuda/bin/cuobjdump','--dump-resource-usage',str(binary)],
                                    capture_output=True,text=True,check=True).stdout
        (part/'resources.txt').write_text(entry_output)
        entries=re.findall(r'Function\s+(\S*sm90_dense_native_kernel[^\s:]*):',entry_output)
        if len(entries)!=1:raise ValueError('probe must contain exactly one native entry')
        size=instructions(binary,entries[0])
        if size<=0:raise ValueError('missing probe SASS instruction count')
        record=dict(first=first,last=last,binary=str(binary),binary_sha256=sha(binary),source_sha256=sha(source),
            ledger=str(part/'ledger.json'),ledger_sha256=sha(part/'ledger.json'),entry=entries[0],
            entry_instructions=size,limit=limit['probe_limit'],inputs_unchanged=True)
        if size>limit['probe_limit']:
            if last-first==1:raise RuntimeError('a single-theta probe exceeds the R5 entry bound')
            record['status']='entry_size_split';attempts.append(record)
            middle=(first+last)//2;build(first,middle);build(middle,last)
        else:
            record['status']='compiled';retained.append(record);attempts.append(record)
            manifest=json.loads(Path(str(base_path)+'.plan.json').read_text())
            manifest['identity_schema']=0
            manifest['native_probe']=dict(family=family,ledger=record['ledger'],
                scope='instrumented isolated stages; base CTG is prerequisite provenance only')
            write(Path(str(binary)+'.plan.json'),manifest)
            write(Path(str(binary)+'.probe-identity.json'),dict(record,
                input_hashes=str(directory/'inputs.json'),input_hashes_sha256=sha(directory/'inputs.json')))
            write(Path(str(binary)+'.serving.json'),dict(decode_mode='L1',decode_loop=1,prefill_mode='L1'))
        write(directory/'builds.json',attempts)

    build(0,len(sources))
    if any(sha(path)!=digest for path,digest in inputs.items()):
        raise ValueError('probe inputs changed while completing the manifest')
    write(Path(str(a.out)+'.probe.json'),dict(family=family,geometries=len(sources),parts=retained,
        input_hashes=str(directory/'inputs.json'),scope='AB1a isolated-stage diagnostics; not an end-to-end executable'))
    print(json.dumps(dict(family=family,parts=len(retained),manifest=str(a.out)+'.probe.json')),flush=True)


if __name__=='__main__':main()
