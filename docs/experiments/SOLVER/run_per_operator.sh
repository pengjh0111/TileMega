# P4.5 acceptance (b): what is a *per-operator* granularity actually worth?
#
# The DP's plans are already committed in raw/plan_<model>.tsv.  This script
# compiles each plan into a real megakernel and measures it the way every other
# timing claim in this repo is measured -- N fresh processes, one timed launch
# each, median reported -- against the uniform plan the same DP chose and
# against the oracle's own measured-best uniform.
#
# Needs a GPU.  Depends on ORACLE's generated sources and fixtures.
#
#   bash docs/experiments/SOLVER/run_per_operator.sh
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "${here}/../../.." && pwd)"
raw="${here}/raw"
build="${repo}/build-phase12"
nvcc="${CUDACXX:-/usr/local/cuda/bin/nvcc}"
runs="${RUNS:-25}"
mkdir -p "${raw}/bin" "${raw}/log" "${raw}/final"

gqa_src="${repo}/docs/experiments/E2E_GEN/raw/generated_e2e.cu"
gqa_fixture="${repo}/docs/experiments/E2E/fixture"
mha_src="${repo}/docs/experiments/P3_GENERALIZATION/raw/generated.cu"
mha_fixture="${repo}/docs/experiments/P3_GENERALIZATION/raw/fixture"
for needed in "${build}/libtilemega.a" "${gqa_src}" "${gqa_fixture}/manifest.json" \
              "${mha_src}" "${mha_fixture}/manifest.json" \
              "${raw}/plan_gqa2.tsv" "${raw}/plan_mha4.tsv"; do
  if [[ ! -e "${needed}" ]]; then
    echo "BLOCKED: ${needed} missing" | tee "${raw}/per_operator_status.txt" >&2
    exit 77
  fi
done

common=(-std=c++17 -O2 -arch=native -lineinfo -Xptxas=-v
  -I"${repo}/include" -I"${repo}/third_party/cutlass/include"
  -I"${repo}/third_party/cutlass/tools/util/include"
  -I"${repo}/third_party/cutlass/test")
link=("${build}/libtilemega.a" -L/usr/local/cuda/lib64 -lcudart)

# ------------------------------------------------------------ plan header ---
# The per-operator plan reaches the compiler as one -include'd header rather
# than a nest of ternary -D flags, so the emitted plan is readable and diffable
# next to the .tsv it came from.  Variant 0 is always the plan's most common
# shape, which makes the uniform arm a plain rebuild of today's defaults.
#   $1 = header path  $2 = plan tsv  $3 = column of the tile fields to honour
#        (5 = full per-operator plan, 9 = split factor only)
emit_plan() {
  local out="$1" tsv="$2" mode="$3"
  python3 - "$out" "$tsv" "$mode" <<'PY'
import sys, collections
out, tsv, mode = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(tsv).read().splitlines()
head = text[0].split('\t')
rows = [l.split('\t') for l in text[1:] if l.strip()]
col = {n: i for i, n in enumerate(head)}
def field(r, name):
    return int(r[col['%s_%s' % (mode, name)]])
shapes = [(field(r, 'tile_m'), field(r, 'tile_n'), field(r, 'tile_k'),
           field(r, 'stages')) for r in rows]
splits = [field(r, 'split_k') for r in rows]
order = list(dict.fromkeys(shapes))
order.sort(key=lambda s: -shapes.count(s))
if len(order) > 4:
    sys.exit("plan needs %d variants; the runtime compiles at most 4" % len(order))
index = {s: i for i, s in enumerate(order)}
base = order[0]
lines = ['// generated by run_per_operator.sh from %s (arm=%s)' %
         (tsv.split("/")[-1], mode),
         '#define TILEMEGA_GEMM_TILE_M %d' % base[0],
         '#define TILEMEGA_GEMM_TILE_N %d' % base[1],
         '#define TILEMEGA_GEMM_TILE_K %d' % base[2],
         '#define TILEMEGA_GEMM_STAGES %d' % base[3],
         '#define TILEMEGA_GEMM_SPLIT_K %d' %
         collections.Counter(splits).most_common(1)[0][0],
         '#define TILEMEGA_GEMM_VARIANT_COUNT %d' % len(order)]
for i, s in enumerate(order[1:], start=1):
    lines += ['#define TILEMEGA_GEMM_V%d_TILE_M %d' % (i, s[0]),
              '#define TILEMEGA_GEMM_V%d_TILE_N %d' % (i, s[1]),
              '#define TILEMEGA_GEMM_V%d_TILE_K %d' % (i, s[2]),
              '#define TILEMEGA_GEMM_V%d_STAGES %d' % (i, s[3])]
if len(order) > 1:
    lines += ['static constexpr int kTileMegaGemmVariantPlan[] = {%s};' %
              ', '.join(str(index[s]) for s in shapes),
              '#define TILEMEGA_GEMM_VARIANT_OF(i) (kTileMegaGemmVariantPlan[(i)])']
if len(set(splits)) > 1:
    lines += ['static constexpr int kTileMegaGemmSplitPlan[] = {%s};' %
              ', '.join(str(s) for s in splits),
              '#define TILEMEGA_GEMM_SPLIT_OF(i) (kTileMegaGemmSplitPlan[(i)])']
open(out, 'w').write('\n'.join(lines) + '\n')
print('%s: %d variants, %d split factors, %d operators' %
      (out.split("/")[-1], len(order), len(set(splits)), len(shapes)))
PY
}

# --------------------------------------------------------------- arms -------
# `uniform_best` is the oracle's own 25-process winner, so the per-operator
# number is compared against the best uniform anyone measured, not only against
# the best uniform the model picked.
declare -A best_uniform=( [gqa2]="16 64 32 3 16" [mha4]="16 64 16 2 16" )

emit_fixed() {  # $1=header $2=tile fields
  read -r m n k s kc <<<"$2"
  cat > "$1" <<EOF
// oracle-measured best uniform configuration
#define TILEMEGA_GEMM_TILE_M ${m}
#define TILEMEGA_GEMM_TILE_N ${n}
#define TILEMEGA_GEMM_TILE_K ${k}
#define TILEMEGA_GEMM_STAGES ${s}
#define TILEMEGA_GEMM_SPLIT_K ${kc}
EOF
}

median() { sort -n | awk '{v[NR]=$1} END {if(NR==0){print "nan";exit} printf "%.6f\n",(NR%2)?v[(NR+1)/2]:(v[NR/2]+v[NR/2+1])/2}'; }

# ------------------------------------------------------------ protocol ------
# Arms are compiled first and then measured *interleaved*, one fresh process
# per arm per round, with the starting arm rotated each round.  Measuring them
# in blocks does not work here: on mha4 two arms compile to the identical plan,
# and run in blocks they separated by 0.64 % at rank-sum p = 1.8e-4 -- a
# "significant" difference between two identical binaries.  Within-session
# drift, not sampling noise, is the dominant term, and only interleaving
# removes it from the arm contrast.
printf 'model\tarm\tvariants\tl05_ms\tl1_ms\tl2_ms\tpass\tmax_rel\tsmem\tctas_per_sm\tgrid\thash\n' \
  > "${raw}/per_operator.tsv"
arms=(uniform split_only per_op best_uniform)

for model in gqa2 mha4; do
  src="${gqa_src}"; fixture="${gqa_fixture}"
  if [[ "${model}" == mha4 ]]; then src="${mha_src}"; fixture="${mha_fixture}"; fi
  for arm in "${arms[@]}"; do
    header="${raw}/plan_${model}_${arm}.h"
    if [[ "${arm}" == best_uniform ]]; then
      emit_fixed "${header}" "${best_uniform[$model]}"
      echo "plan_${model}_${arm}.h: fixed ${best_uniform[$model]}"
    else
      emit_plan "${header}" "${raw}/plan_${model}.tsv" "${arm}"
    fi
    "${nvcc}" "${src}" "${common[@]}" -include "${header}" "${link[@]}" \
      -o "${raw}/bin/${model}_${arm}" 2> "${raw}/log/${model}_${arm}.ptxas"
  done

  echo "== ${model}: ${runs} interleaved rounds over ${#arms[@]} arms"
  for ((round = 0; round < runs; ++round)); do
    for ((slot = 0; slot < ${#arms[@]}; ++slot)); do
      arm=${arms[$(( (round + slot) % ${#arms[@]} ))]}
      "${repo}/scripts/gpu_stat_run.sh" -n 1 -t 120 -l "perop_${model}_${arm}" \
        -k -o "${raw}/final/${model}_${arm}/r${round}" \
        -- "${raw}/bin/${model}_${arm}" "${fixture}" \
        >> "${raw}/log/${model}_${arm}.final" 2>&1
    done
  done

  for arm in "${arms[@]}"; do
    mapfile -t logs < <(find "${raw}/final/${model}_${arm}" -name 'run_*.log' | sort)
    l05=$(grep -h '^E2E_TIME' "${logs[@]}" | sed -E 's/.*l05_ms=([0-9.]+).*/\1/' | median)
    l1=$(grep -h '^E2E_TIME' "${logs[@]}" | sed -E 's/.*l1_ms=([0-9.]+).*/\1/' | median)
    l2=$(grep -h '^E2E_TIME' "${logs[@]}" | sed -E 's/.* l2_ms=([0-9.]+).*/\1/' | median)
    pass=$(grep -h -c '^RESULT status=PASS' "${logs[@]}" | awk '{t+=$1} END{print t+0}')
    hash=$(grep -h '^E2E_HASH' "${logs[@]}" | sed -E 's/.*l05=([0-9a-f]+).*/\1/' | sort -u | paste -sd, -)
    # The bitwise hash is *expected* to move with the split factor: split-K
    # changes the association of the k reduction.  Correctness is therefore the
    # harness's own comparison against the CPU reference, reported here so the
    # arms can be compared on it rather than on a hash that cannot match.
    rel=$(grep -h '^E2E_DIFF' "${logs[@]}" | sed -E 's/.*l05_vs_l0_mismatch=[0-9]+ max_abs=[0-9.e+-]+ max_rel=([0-9.e+-]+).*/\1/' | sort -g | tail -1)
    smem=$(grep -h '^E2E_RESOURCE' "${logs[@]}" | sed -E 's/.*smem=([0-9]+).*/\1/' | sort -u | paste -sd, -)
    ctas=$(grep -h '^E2E_RESOURCE' "${logs[@]}" | sed -E 's/.*ctas_per_sm=([0-9]+).*/\1/' | sort -u | paste -sd, -)
    grid=$(grep -h '^E2E_RESOURCE' "${logs[@]}" | sed -E 's/.*grid=([0-9]+).*/\1/' | sort -u | paste -sd, -)
    variants=$( { grep -c '^#define TILEMEGA_GEMM_V[123]_TILE_M' "${raw}/plan_${model}_${arm}.h" || true; } )
    printf '%s\t%s\t%d\t%s\t%s\t%s\t%s/%s\t%s\t%s\t%s\t%s\t%s\n' \
      "${model}" "${arm}" "$((variants + 1))" "${l05}" "${l1}" "${l2}" \
      "${pass}" "${#logs[@]}" "${rel}" "${smem}" "${ctas}" "${grid}" "${hash}" \
      | tee -a "${raw}/per_operator.tsv"
  done
done

# Every arm has to be correct before any of them is fast: the harness compares
# each launch against the CPU reference itself, so the gate is that comparison
# on every one of the fresh processes, not the output hash (split-K legally
# moves the hash by reassociating the k reduction).
awk -F'\t' 'NR>1 {split($7,p,"/"); if (p[1]+0 != p[2]+0 || p[2]+0 == 0) {
    print "FAIL: " $1 " " $2 " passed " $7; bad=1 } }
  END {if (bad) exit 1; print "every arm PASSed the reference comparison in every fresh process"}' \
  "${raw}/per_operator.tsv"

python3 "${here}/summarize_per_operator.py" "${raw}" \
  > "${raw}/per_operator_summary.txt"
cat "${raw}/per_operator_summary.txt"
