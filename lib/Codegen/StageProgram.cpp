namespace tilemega::codegen {
namespace {
std::string Quote(std::string const& value) {
  std::string result = "\"";
  for (unsigned char c : value) {
    switch (c) {
      case '\\': result += "\\\\"; break;
      case '"': result += "\\\""; break;
      case '\n': result += "\\n"; break;
      case '\r': result += "\\r"; break;
      case '\t': result += "\\t"; break;
      default:
        if (c < 32 || c >= 127) {
          result += '\\';
          result += char('0' + ((c >> 6) & 7));
          result += char('0' + ((c >> 3) & 7));
          result += char('0' + (c & 7));
        } else result += char(c);
    }
  }
  return result + '"';
}
}  // namespace

std::string EmitStageProgram(StageProgramSpec const& s) {
  auto fail = [](char const* why) { throw std::invalid_argument(std::string("stage program: ") + why); };
  if (s.version != 2 && s.version != 3) fail("version must be 2 or 3");
  if (s.stages.empty() || s.tail_stages.empty() || s.loop.end.empty()) fail("a loop and a step tail are required");
  if (s.kind == StageProgramKind::kPrompt && s.terminal_condition.empty()) fail("prompt requires a final-token tail predicate");
  std::map<std::string, StageProgramStage const*> stages;
  for (auto const* list : {&s.stages, &s.tail_stages})
    for (auto const& stage : *list) {
      if (stage.name.empty() || stage.body_type.empty() || stage.shape_type.empty() || stage.operands.empty() ||
          stage.prefetch_operands.empty() || stage.next.empty()) fail("incomplete stage");
      if (!stages.emplace(stage.name, &stage).second) fail("duplicate stage name");
    }
  for (auto const& item : stages) {
    auto const& stage = *item.second;
    if (!stages.count(stage.next)) fail("unknown prefetch target");
    if (!stage.terminal_next.empty() && (!stages.count(stage.terminal_next) || stage.terminal_body.empty() ||
                                        stage.terminal_prefetch_operands.empty())) fail("incomplete terminal edge");
  }
  for (std::size_t i = 0; i + 1 < s.stages.size(); ++i)
    if (s.stages[i].next != s.stages[i + 1].name) fail("loop stage order disagrees with its prefetch edges");
  auto const& last = s.stages.back();
  if (last.next != s.stages.front().name || last.terminal_next != s.tail_stages.front().name)
    fail("loop back edge or terminal edge disagrees with program order");
  for (std::size_t i = 0; i < s.tail_stages.size(); ++i)
    if (s.tail_stages[i].next != (i + 1 < s.tail_stages.size() ? s.tail_stages[i + 1].name : s.stages.front().name))
      fail("tail edge disagrees with program order");

  std::ostringstream o;
  o << "// Generated by tilemega::codegen::EmitStageProgram.\n";
  for (auto const& include : s.includes) o << "#include <" << include << ">\n";
  o << "\nnamespace " << s.namespace_name << " {\n"
    << "using namespace tilemega;\nusing namespace tilemega::backend::mx;\n"
    << "namespace mx = tilemega::codegen::mx;\n" << s.binding_declaration << '\n'
    << "struct " << s.plan_name << " {\n" << s.plan_declarations << '\n'
    << "  static constexpr int kStageCount = (" << s.loop.end << " - (" << s.loop.begin << ")) * "
    << s.stages.size() << " + " << s.tail_stages.size() << ";\n"
    << "  static constexpr int kProgramKind = " << int(s.kind) << ";\n";
  for (auto const* list : {&s.stages, &s.tail_stages})
    for (auto const& stage : *list) {
      o << "  using " << stage.name << " = " << stage.body_type << ";\n"
        << "  using " << stage.name << "Shape = " << stage.shape_type << ";\n";
      if (!stage.terminal_body.empty())
        o << "  using " << stage.name << "Last = " << stage.terminal_body << ";\n";
    }
  auto const& entry = s.stages.front();
  o << "  template <class Self>\n  __device__ __forceinline__ static auto EntryPrefetch(" << s.operand_parameters
    << ") {\n    return " << entry.name << "::Prefetch("
    << (s.entry_prefetch_operands.empty() ? entry.prefetch_operands : s.entry_prefetch_operands)
    << ", " << entry.name << "Shape{});\n  }\n"
    << (s.version == 3 ? "  template <class Self, class Arrive, class Wait, class Run>\n" :
                        "  template <class Self, class Barrier, class Run>\n")
    << "  __device__ __forceinline__ static void RunStep("
    << s.run_parameters << ", typename " << entry.name << "::Prefetched& pf_" << entry.name
    << (s.version == 3 ? ", Arrive arrive, Wait wait, Run run) {\n" : ", Barrier barrier, Run run) {\n")
    << "#pragma unroll 1\n    for (int " << s.loop.index << " = " << s.loop.begin << "; " << s.loop.index
    << " < " << s.loop.end << "; ++" << s.loop.index << ") {\n";
  auto call = [&](StageProgramStage const& stage, std::string const& body, std::string const& target,
                  std::string const& ops, bool declare, std::string const& indent) {
    o << indent << (declare ? "auto " : "") << "pf_" << target << " = mx::RunStageV" << s.version << "<" << body
      << ">(run(" << stage.diagnostic_class << "), pf_" << stage.name << ", " << stage.operands << ", "
      << stage.name << "Shape{}, smem, [&] { " << (s.version == 3 ? "arrive(); " : "")
      << "return " << target << "::Prefetch(" << ops << ", "
      << target << "Shape{}); }" << (s.version == 3 ? ", arrive" : "") << ");\n";
  };
  auto tail = [&](std::string const& indent) {
    for (std::size_t i = 0; i < s.tail_stages.size(); ++i) {
      auto const& stage = s.tail_stages[i];
      auto const& next = *stages.at(stage.next);
      call(stage, stage.name, stage.next,
           stage.next_prefetch_operands.empty() ? next.prefetch_operands : stage.next_prefetch_operands,
           i + 1 < s.tail_stages.size(), indent);
      o << indent << (s.version == 3 ? "wait();\n" : "barrier();\n");
    }
  };
  for (std::size_t i = 0; i < s.stages.size(); ++i) {
    auto const& stage = s.stages[i];
    if (i + 1 == s.stages.size()) {
      o << "      if (" << s.loop.index << " + 1 == " << s.loop.end;
      if (!s.terminal_condition.empty()) o << " && (" << s.terminal_condition << ")";
      o << ") {\n";
      // The terminal packet is consumed before leaving its defining scope.
      call(stage, stage.name + "Last", stage.terminal_next, stage.terminal_prefetch_operands, true, "        ");
      o << (s.version == 3 ? "        wait();\n" : "        barrier();\n");
      tail("        ");
      o << "        break;\n      }\n";
    }
    auto const& next = *stages.at(stage.next);
    call(stage, stage.name, stage.next,
         stage.next_prefetch_operands.empty() ? next.prefetch_operands : stage.next_prefetch_operands,
         i + 1 != s.stages.size(), "      ");
    o << (s.version == 3 ? "      wait();\n" : "      barrier();\n");
  }
  o << "    }\n";
  o << "  }\n};\ninline constexpr " << s.buffer_row_type << " kBuffers[] = {\n";
  for (auto const& b : s.external_buffers)
    o << "  {" << Quote(b.name) << ", " << b.dtype_expr << ", " << b.constant << "ull, " << b.per_batch
      << "ull, " << (b.recipe.empty() ? "nullptr" : Quote(b.recipe)) << ", " << b.slot_expr << ", " << b.layer << "},\n";
  o << "};\n}  // namespace " << s.namespace_name << '\n';
  if (!s.runtime_header.empty()) o << "\n#include <" << s.runtime_header << ">\n";
  return o.str();
}
}  // namespace tilemega::codegen
